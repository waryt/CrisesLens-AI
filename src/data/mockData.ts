function enrichWithTrecMetadata(reports: EmergencyReport[]): EmergencyReport[] {
  return reports.map((r) => {
    let trecEventId = r.trecEventId;
    let trecEventName = r.trecEventName;
    let infoCat = r.informationCategory;
    let offCat = r.officialCategory;
    const offPrio = r.officialPriority || r.severity;

    if (!trecEventId) {
      if (r.clusterId === 'CRISIS-17') {
        trecEventId = 'trecis2020-A-test.035';
        trecEventName = 'Hurricane Florence (Sector 4 Flooding)';
      } else if (r.clusterId === 'CRISIS-09') {
        trecEventId = 'trecis2020-A-test.039';
        trecEventName = 'Hurricane Dorian (Hospital Access Blockage)';
      } else if (r.clusterId === 'CRISIS-22') {
        trecEventId = 'trecis2020-A-test.036';
        trecEventName = 'California Wildfire (Camp Fire Depot)';
      } else if (r.clusterId === 'CRISIS-14') {
        trecEventId = 'trecis2020-A-test.042';
        trecEventName = 'Cyclone Fani (Shelter Evacuation Bottleneck)';
      } else if (r.clusterId === 'CRISIS-05') {
        trecEventId = 'trecis2020-A-test.040';
        trecEventName = 'Kincade Fire (Substation Arc & Grid Spark)';
      } else if (r.clusterId === 'CRISIS-03') {
        trecEventId = 'trecis2020-A-test.041';
        trecEventName = 'Dallas Tornado (Highway 102 Debris)';
      } else {
        trecEventId = 'trecis2020-A-test.035';
        trecEventName = 'Hurricane Florence (Sector 4 Flooding)';
      }
    }

    if (!infoCat) {
      if (r.crisisType === 'Medical Emergency') infoCat = 'MedicalNeeded';
      else if (r.crisisType === 'Road Blockage') infoCat = 'RoadBlockage';
      else if (r.crisisType === 'Flooding') infoCat = 'SearchAndRescue';
      else if (r.crisisType === 'Fire') infoCat = 'CallToAction';
      else if (r.crisisType === 'Power Grid Failure') infoCat = 'ServiceDisruption';
      else if (r.crisisType === 'Hazardous Material') infoCat = 'ReportUrgent';
      else infoCat = 'SearchAndRescue';
    }

    if (!offCat) offCat = infoCat;

    return {
      ...r,
      trecEventId,
      trecEventName,
      informationCategory: infoCat,
      officialCategory: offCat,
      officialPriority: offPrio,
      isCategoryMatch: r.isCategoryMatch ?? true,
      isPriorityMatch: r.isPriorityMatch ?? true,
      isCorrectlyClustered: r.isCorrectlyClustered ?? true,
    };
  });
}

